#!/usr/bin/env python3
"""Pack authored rear views for the v7 review; preserve other rear silhouettes.

Input: JSON list of {id, path, prompt}; one image per lineage, containing only
the changed Forms in review order. No artwork is generated by this packer.
"""
import hashlib
import io
import json
import os
import subprocess
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
review = json.loads((ROOT / 'docs/roster-art-review-v7.json').read_text())
audit = json.loads((ROOT / 'docs/rear-atlas-audit.json').read_text())
records = {r['id']: r for r in audit['records']}
jobs = {r['id']: r for r in json.loads(Path(sys.argv[1]).read_text())}
assert set(jobs) == {r['id'] for r in review['lineages']}
report = {'revision': 7, 'generator': 'OpenAI image_gen', 'forms': 0, 'lineages': []}

for entry in review['lineages']:
    ident, forms = entry['id'], entry['forms']
    job, prior = jobs[ident], records[ident]
    original = Image.open(io.BytesIO(subprocess.check_output(
        ['git', 'show', f'HEAD:assets/battle-back/{ident}.webp'], cwd=ROOT))).convert('RGBA')
    atlas = original.copy()
    image = Image.open(job['path']).convert('RGBA')
    assert image.getchannel('A').getextrema()[0] == 0, (ident, 'missing transparency')
    # Single-form renders fill their canvas; multi-form sheets have equal zones.
    sprites, boxes = [], []
    for index, form in enumerate(forms):
        left, right = round(index * image.width / len(forms)), round((index + 1) * image.width / len(forms))
        sprite = image.crop((left, 0, right, image.height))
        bounds = sprite.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
        assert bounds, (ident, form, 'empty sprite')
        assert bounds[0] > 0 and bounds[1] > 0 and bounds[2] < sprite.width and bounds[3] < sprite.height, (ident, form, 'clipped source')
        sprites.append(sprite.crop(bounds))
        boxes.append([left + bounds[0], bounds[1], left + bounds[2], bounds[3]])
    zones = []
    for form in forms:
        index = form - 1
        bounds = prior['forms'][index]['bounds']
        left = 0 if index == 0 else (prior['forms'][index - 1]['bounds'][2] + bounds[0]) // 2
        right = original.width if index == 2 else (bounds[2] + prior['forms'][index + 1]['bounds'][0]) // 2
        zones.append((left, right))
    scale = min([232 / max(s.height for s in sprites)] + [(right - left - 16) / sprite.width for sprite, (left, right) in zip(sprites, zones)])
    for sprite, (left, right) in zip(sprites, zones):
        sprite = sprite.resize((max(1, round(sprite.width * scale)), max(1, round(sprite.height * scale))), Image.Resampling.LANCZOS)
        atlas.paste((0, 0, 0, 0), (left, 0, right, atlas.height))
        atlas.alpha_composite(sprite, (left + (right - left - sprite.width) // 2, 246 - sprite.height))
    target = ROOT / f'assets/battle-back/{ident}.webp'
    encoded = io.BytesIO()
    atlas.save(encoded, 'WEBP', lossless=True, exact=True, method=6)
    temporary = target.with_suffix('.webp.tmp')
    with temporary.open('wb') as stream:
        stream.write(encoded.getvalue())
        stream.flush()
        os.fsync(stream.fileno())
    temporary.replace(target)
    saved = Image.open(target).convert('RGBA')
    unchanged = []
    for index in range(3):
        if index + 1 not in forms:
            x, y, w, h = prior['forms'][index]['frame']
            box = (x, y, x + w, y + h)
            assert original.crop(box).tobytes() == saved.crop(box).tobytes(), (ident, index, 'unchanged rear altered')
            unchanged.append(index + 1)
    report['forms'] += len(forms)
    report['lineages'].append({'id': ident, 'forms': forms, 'frontAtlas': entry['atlas'],
        'frontSha256': entry['atlasSha256'], 'rearAtlas': './' + str(target.relative_to(ROOT)),
        'rearSha256': hashlib.sha256(target.read_bytes()).hexdigest(),
        'sourceSha256': hashlib.sha256(Path(job['path']).read_bytes()).hexdigest(),
        'sourceBoxes': boxes, 'prompt': job['prompt'], 'unchangedFormsVerified': unchanged})
    print(f'{ident}: {forms}; unchanged rear Forms verified: {unchanged}')
assert report['forms'] == 47
(ROOT / 'docs/reviewed-rear-art-v7.json').write_text(json.dumps(report, indent=2) + '\n')
