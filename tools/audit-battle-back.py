#!/usr/bin/env python3
"""Audit all rear atlases and generate source-frame metadata without editing artwork.

Requires Pillow. Run from any directory; --check compares committed metadata.
The alpha threshold ignores barely visible background residue. Floating details
remain attached to the closest horizontal silhouette group, never discarded.
"""
import argparse, hashlib, json
from pathlib import Path
from PIL import Image
ROOT=Path(__file__).resolve().parent.parent
THRESHOLD=8
PADDING=4

def inspect(path):
    im=Image.open(path).convert('RGBA'); w,h=im.size
    alpha=im.getchannel('A'); mask=alpha.point(lambda a:255 if a>THRESHOLD else 0)
    occupied=[mask.crop((x,0,x+1,h)).getbbox() is not None for x in range(w)]
    groups=[]; start=None
    for x,solid in enumerate(occupied+[False]):
        if solid and start is None: start=x
        if not solid and start is not None: groups.append([start,x]); start=None
    raw_groups=[r[:] for r in groups]
    if len(groups)<3: raise ValueError(f'{path.name}: cannot identify three separate forms')
    while len(groups)>3:
        index=min(range(len(groups)-1),key=lambda n:groups[n+1][0]-groups[n][1])
        groups[index:index+2]=[[groups[index][0],groups[index+1][1]]]
    frames=[]; details=[]
    for n,(left,right) in enumerate(groups):
        bounds=mask.crop((left,0,right,h)).getbbox()
        core=[left+bounds[0],bounds[1],left+bounds[2],bounds[3]]
        zone_left=0 if n==0 else (groups[n-1][1]+left)//2
        zone_right=w if n==2 else (right+groups[n+1][0])//2
        box=[max(zone_left,core[0]-PADDING),max(0,core[1]-PADDING),min(zone_right,core[2]+PADDING),min(h,core[3]+PADDING)]
        frame=[box[0],box[1],box[2]-box[0],box[3]-box[1]]
        total=sum(mask.crop((left,0,right,h)).histogram()[1:])
        captured=sum(mask.crop(tuple(box)).histogram()[1:])
        if captured!=total: raise ValueError(f'{path.name} form {n}: incomplete or contaminated frame')
        # Faint glow can touch an edge; opaque body pixels must remain inside.
        solid=alpha.point(lambda a:255 if a>32 else 0).crop((left,0,right,h)).getbbox()
        if solid and (left+solid[0]<=0 or solid[1]<=0 or left+solid[2]>=w or solid[3]>=h): raise ValueError(f'{path.name} form {n}: body artwork touches atlas edge')
        frames.append(frame); details.append({'form':n,'bounds':core,'frame':frame,'visible_pixels':total,'captured_pixels':captured})
    return {'id':path.stem,'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'size':[w,h], 'alpha_runs':raw_groups,'crossed_equal_thirds':any(a<c<b for a,b in groups for c in [w//3,2*w//3]),'forms':details}, frames

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    records=[];frames={}
    for path in sorted((ROOT/'assets/battle-back').glob('*.webp')):
        record,rects=inspect(path);records.append(record);frames[path.stem]=rects
    if len(records)!=150: raise ValueError(f'Expected 150 rear atlases; found {len(records)}')
    audit={'version':1,'alpha_threshold':THRESHOLD,'padding':PADDING,'atlases':len(records),'forms':len(records)*3,'atlases_crossing_equal_thirds':sum(r['crossed_equal_thirds'] for r in records),'records':records}
    module='// Audited source rectangles [x,y,width,height]. Generated by tools/audit-battle-back.py.\n// Artwork uses uneven spacing; never infer built-in frames by splitting into thirds.\nexport const BATTLE_BACK_FRAMES=Object.freeze('+json.dumps(frames,separators=(',',':'))+');\n'
    outputs={ROOT/'battle-back-frames.mjs':module,ROOT/'docs/rear-atlas-audit.json':json.dumps(audit,indent=2)+'\n'}
    for path,content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text()!=content: raise ValueError(f'{path.relative_to(ROOT)} needs regeneration')
        else: path.write_text(content)
    print(f"Audited {len(records)} rear atlases / {len(records)*3} forms; {audit['atlases_crossing_equal_thirds']} atlases cross the old cuts. All frames capture their complete form without neighboring silhouettes.")
if __name__=='__main__':main()
